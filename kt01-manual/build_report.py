def shade(cell, color):
    tc = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), color)
    tc.append(shd)


def borders(table):
    el = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        b = OxmlElement(f"w:{side}")
        b.set(qn("w:val"), "single")
        b.set(qn("w:sz"), "4")
        b.set(qn("w:color"), "C7C7CC")
        el.append(b)
    table._tbl.tblPr.append(el)


def table(doc, header, rows, widths=None, size=8.5):
    t = doc.add_table(rows=1, cols=len(header))
    borders(t)
    for c, v in zip(t.rows[0].cells, header):
        c.text = v
        c.paragraphs[0].runs[0].bold = True
        shade(c, "F2F2F7")
    for row in rows:
        cells = t.add_row().cells
        for c, v in zip(cells, row):
            c.text = str(v)
            if str(v).startswith("Не пройден"):
                c.paragraphs[0].runs[0].font.color.rgb = RGBColor(0xC0, 0x1C, 0x1C)
    for r in t.rows:
        for i, c in enumerate(r.cells):
            if widths:
                c.width = Cm(widths[i])
            for p in c.paragraphs:
                for run in p.runs:
                    run.font.size = Pt(size)
    return t


def image(doc, name, width=15.5, caption=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(S / name), width=Cm(width))
    if caption:
        c = doc.add_paragraph(caption)
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.runs[0].font.size = Pt(9)
        c.runs[0].italic = True


